/**
 * The generated `ios/build/pod-binaries` package (spec goal 2.5): one product per root pod a library names, listing
 * every headers-only binary target that root reaches and a wrapper C target that depends on the source pods' SwiftPM
 * products (goal 3). The xcframeworks and the thin archives are copies of the wrapped cache (row 85: an edit here never
 * reaches the cache); the archives are linked once, by `-force_load` on the App target (`PodsLinks`). Rebuilt on every
 * build, never under node_modules.
 */
import { existsSync, readdirSync, realpathSync } from "node:fs";
import { copyFile, mkdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import type { PodEntry } from "../config.js";
import type { ProjectPaths } from "../paths.js";
import { swapIn } from "../pipeline/rnArtifacts.js";
import { packageRoot } from "../tools/exec.js";
import { PODS_LINK, PodsError } from "./format.js";
import type { Resolution } from "./resolve.js";
import type { WrappedPod } from "./wrap.js";

export const POD_BINARIES_PACKAGE = "pod-binaries";

/** What the App target links for the binary pods; `emptyTargets` are the source packages' targets without sources. */
export interface PodsLinks {
  archives: string[];
  frameworks: string[];
  libraries: string[];
  weakFrameworks: string[];
  emptyTargets: string[];
}

export interface StagedPods {
  dir: string;
  links: PodsLinks;
  binaryTargets: string[];
  products: string[];
}

/** What the `pods` step hands to staging: the resolution and the wrapped tree of each binary pod. */
export interface PodsResult {
  resolution: Resolution;
  wrapped: WrappedPod[];
}

export interface PodBinariesInput {
  products: { name: string; binaryTargets: string[]; sourceProducts: { product: string; package: string }[] }[];
  sourcePackages: { url: string; exact: string }[];
  iosMin: string;
}

const HEADER = "// Generated by rn-xtool from rn-xtool-pods.lock.json and its cache. Do not edit; rn-xtool build rewrites it.";
const byText = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const sortedUnique = (items: Iterable<string>): string[] => [...new Set(items)].sort(byText);

/** SwiftPM's identity of a package URL, as the scaffolder's `spmPackageIdentity`: its last component, lowercased. */
export function packageIdentity(url: string): string {
  return path.posix.basename(url).replace(/\.git$/, "").toLowerCase();
}

const wrapperName = (product: string): string => `${product}Wrapper`;
const cName = (name: string): string => name.replace(/[^A-Za-z0-9_]/g, "_");

/** The products a source dependency's subspecs name (the entry's products for the pod itself). */
function sourceProducts(entry: PodEntry, subspecs: readonly string[]): string[] {
  const all = entry.products ?? (entry.product !== undefined ? [entry.product] : []);
  if (subspecs.length === 0) return all;
  return subspecs.flatMap((sub) => entry.subspecs?.[sub] ?? all);
}

/**
 * The package's contents from the resolution and the wrapped pods: one product per root pod, with the binary targets
 * of every pod that root reaches (the union of what each library's subspecs need) and the source products those pods
 * depend on. Stops on two pods that make one module (row 38) and on a wrapper named like a binary target.
 */
export function podBinariesInput(result: PodsResult, iosMin: string): PodBinariesInput {
  const { resolution, wrapped } = result;
  // Archives come from the wrapped pods and link flags from the resolution: the two must name the same pods (review M5).
  const resolved = new Set(resolution.binary.map((b) => `${b.pod} ${b.version}`));
  const made = new Set(wrapped.map((w) => `${w.pod} ${w.version}`));
  const odd = [
    ...[...made].filter((p) => !resolved.has(p)).map((p) => `${p} too`),
    ...[...resolved].filter((p) => !made.has(p)).map((p) => `${p} missing`),
  ];
  if (odd.length > 0) throw new Error(`internal error: the wrapped CocoaPods binaries (${odd.join(", ")}) are not the resolved ones`);
  const owner = new Map<string, WrappedPod>();
  for (const w of [...wrapped].sort((a, b) => byText(a.pod, b.pod))) {
    for (const f of w.frameworks) {
      const first = owner.get(f.name);
      if (first !== undefined && first.pod !== w.pod) {
        throw new PodsError(
          `Two CocoaPods binaries make the module ${f.name}: ${first.pod} ${first.version} and ${w.pod} ${w.version}. rn-xtool cannot link both. See ${PODS_LINK}`,
        );
      }
      owner.set(f.name, w);
    }
  }
  const binaryPods = new Map(resolution.binary.map((b) => [b.pod, b]));
  const used = new Map<string, string>();
  const products = [...resolution.roots]
    .sort((a, b) => byText(a.pod, b.pod))
    .map(({ pod: root }) => {
      const reached = new Set(resolution.binary.filter((b) => b.roots.includes(root)).map((b) => b.pod));
      const binaryTargets = sortedUnique(wrapped.filter((w) => reached.has(w.pod)).flatMap((w) => w.frameworks.map((f) => f.name)));
      const wrapper = wrapperName(root);
      const taken = owner.get(wrapper);
      if (taken !== undefined) {
        throw new PodsError(`The wrapper target ${wrapper} would have the name of a binary target of ${taken.pod}. See ${PODS_LINK}`);
      }
      const deps: { product: string; package: string }[] = [];
      for (const source of resolution.sources) {
        const needed = source.requiredBy.some((r) => reached.has(r.from) || (!binaryPods.has(r.from) && r.from === root));
        if (!needed) continue;
        const pkg = packageIdentity(source.entry.url);
        used.set(source.entry.url, source.entry.exact);
        for (const product of sourceProducts(source.entry, source.subspecs)) {
          if (!deps.some((d) => d.product === product && d.package === pkg)) deps.push({ product, package: pkg });
        }
      }
      deps.sort((a, b) => byText(a.package, b.package) || byText(a.product, b.product));
      return { name: root, binaryTargets, sourceProducts: deps };
    });
  return {
    products,
    sourcePackages: [...used].sort(([a], [b]) => byText(a, b)).map(([url, exact]) => ({ url, exact })),
    iosMin,
  };
}

const q = (s: string): string => `"${s}"`;

/** The package's `Package.swift`: deterministic, every list sorted, relative paths only. */
export function renderPodBinariesPackage(i: PodBinariesInput): string {
  const products = [...i.products].sort((a, b) => byText(a.name, b.name));
  const binaryTargets = sortedUnique(products.flatMap((p) => p.binaryTargets));
  const packages = [...i.sourcePackages].sort((a, b) => byText(a.url, b.url));
  const productLines = products
    .map((p) => `        .library(name: ${q(p.name)}, targets: [${[...sortedUnique(p.binaryTargets), wrapperName(p.name)].map(q).join(", ")}]),\n`)
    .join("");
  const packageLines = packages.map((p) => `        .package(url: ${q(p.url)}, exact: ${q(p.exact)}),\n`).join("");
  const binaryLines = binaryTargets.map((t) => `        .binaryTarget(name: ${q(t)}, path: ${q(`xcframeworks/${t}.xcframework`)}),\n`).join("");
  const wrapperLines = products
    .map((p) => {
      const name = wrapperName(p.name);
      const deps = [...p.sourceProducts].sort((a, b) => byText(a.package, b.package) || byText(a.product, b.product));
      const depsBlock =
        deps.length > 0
          ? `            dependencies: [\n${deps.map((d) => `                .product(name: ${q(d.product)}, package: ${q(d.package)}),\n`).join("")}            ],\n`
          : "";
      return `        .target(\n            name: ${q(name)},\n${depsBlock}            path: ${q(`Sources/${name}`)}\n        ),\n`;
    })
    .join("");
  return `// swift-tools-version: 6.0
${HEADER}
import PackageDescription

let package = Package(
    name: ${q(POD_BINARIES_PACKAGE)},
    platforms: [.iOS(${q(i.iosMin)})],
    products: [
${productLines}    ],
    dependencies: [
${packageLines}    ],
    targets: [
${binaryLines}${wrapperLines}    ]
)
`;
}

/** `src`'s tree at `dest`: folders made, files copied (row 85: never the cache's own inodes). */
async function copyTree(src: string, dest: string): Promise<void> {
  await mkdir(dest, { recursive: true });
  for (const e of readdirSync(src, { withFileTypes: true })) {
    const from = path.join(src, e.name);
    const to = path.join(dest, e.name);
    if (e.isDirectory()) await copyTree(from, to);
    else await copyFile(from, to);
  }
}

/** Whether `p`, resolved through the links of its nearest existing folder, has a node_modules segment. */
function underNodeModules(p: string): boolean {
  let existing = path.resolve(p);
  const rest: string[] = [];
  while (!existsSync(existing) && path.dirname(existing) !== existing) {
    rest.unshift(path.basename(existing));
    existing = path.dirname(existing);
  }
  const real = path.join(realpathSync(existing), ...rest);
  return [path.resolve(p), real].some((x) => x.split(path.sep).includes("node_modules"));
}

/**
 * React Native's floor for the app's manifests, read as the scaffolder reads it (`resolveAppIosDeploymentTarget`): the
 * injected xcodeproj, else the only one in ios/, else React Native's minimum. SwiftPM refuses a product whose minimum
 * is above its dependent's (G1), so pod-binaries takes the scaffolds' floor, not rn-xtool's IOS_MIN.
 */
export function appDeploymentTarget(paths: ProjectPaths): string {
  const spm = path.join(packageRoot(), "vendor", "rn-spm", "spm");
  const req = createRequire(import.meta.url);
  const target = req(path.join(spm, "ios-deployment-target.js")) as {
    MIN_IOS_VERSION_SUPPORTED: string;
    resolveIosDeploymentTarget(o: { xcodeprojPath: string | null; targetUuid?: string | null; targetName?: string | null }): string | null;
  };
  const xcodeproj = req(path.join(spm, "generate-spm-xcodeproj.js")) as {
    findInjectedXcodeproj(appRoot: string): string | null;
    readMarker(xcodeprojPath: string): { targetUuid?: string } | null;
  };
  let project = xcodeproj.findInjectedXcodeproj(paths.ios);
  if (project === null) {
    let names: string[] = [];
    try {
      names = readdirSync(paths.ios, { withFileTypes: true })
        .filter((e) => e.isDirectory() && e.name.endsWith(".xcodeproj"))
        .map((e) => e.name);
    } catch {
      // no ios/
    }
    project = names.length === 1 ? path.join(paths.ios, names[0]!) : null;
  }
  const read =
    project !== null
      ? target.resolveIosDeploymentTarget({ xcodeprojPath: project, targetUuid: xcodeproj.readMarker(project)?.targetUuid ?? null, targetName: null })
      : null;
  return read ?? target.MIN_IOS_VERSION_SUPPORTED;
}

let sequence = 0;

/**
 * Removes and rebuilds `ios/build/pod-binaries` (assembled per pid, swapped in whole): `Package.swift`, `.gitignore`
 * (`*`), `xcframeworks/<Name>.xcframework` and `archives/lib<Name>.a` copied from the cache, and per product
 * `Sources/<Product>Wrapper/{wrapper.c,include/<Product>Wrapper.h}`. `iosMin` is the package's platform, the app's
 * deployment target by default. Throws if the folder would be under node_modules.
 */
export async function stagePodBinaries(
  paths: ProjectPaths,
  result: PodsResult,
  opts: { iosMin?: string } = {},
): Promise<StagedPods> {
  const dir = paths.podBinaries;
  if (underNodeModules(dir)) {
    throw new PodsError(`rn-xtool writes CocoaPods binaries only outside node_modules, and ${dir} is inside it. See ${PODS_LINK}`);
  }
  const input = podBinariesInput(result, opts.iosMin ?? appDeploymentTarget(paths));
  const n = sequence++;
  const tmp = `${dir}.tmp-${process.pid}-${n}`;
  const archives: string[] = [];
  try {
    await rm(tmp, { recursive: true, force: true });
    await mkdir(tmp, { recursive: true });
    for (const w of result.wrapped) {
      for (const f of w.frameworks) {
        await copyTree(f.xcframework, path.join(tmp, "xcframeworks", `${f.name}.xcframework`));
        if (f.archive === undefined) continue;
        await mkdir(path.join(tmp, "archives"), { recursive: true });
        await copyFile(f.archive, path.join(tmp, "archives", `lib${f.name}.a`));
        archives.push(path.join(dir, "archives", `lib${f.name}.a`));
      }
    }
    for (const p of input.products) {
      const name = wrapperName(p.name);
      const sources = path.join(tmp, "Sources", name);
      await mkdir(path.join(sources, "include"), { recursive: true });
      const comment = `// Generated by rn-xtool: ${p.name}'s link to its source dependencies.\n`;
      await writeFile(path.join(sources, "include", `${name}.h`), `${comment}void rn_xtool_${cName(name)}(void);\n`);
      await writeFile(path.join(sources, "wrapper.c"), `${comment}#include "${name}.h"\n\nvoid rn_xtool_${cName(name)}(void) {}\n`);
    }
    await writeFile(path.join(tmp, "Package.swift"), renderPodBinariesPackage(input));
    await writeFile(path.join(tmp, ".gitignore"), "*\n");
    await mkdir(path.dirname(dir), { recursive: true });
    await swapIn(tmp, dir, `${dir}.old-${process.pid}-${n}`);
  } finally {
    await rm(tmp, { recursive: true, force: true }).catch(() => undefined);
  }
  const layers = result.resolution.binary.flatMap((b) => b.layers);
  return {
    dir,
    links: {
      archives: archives.sort(byText),
      frameworks: sortedUnique(layers.flatMap((l) => l.frameworks)),
      libraries: sortedUnique(layers.flatMap((l) => l.libraries)),
      weakFrameworks: sortedUnique(layers.flatMap((l) => l.weakFrameworks)),
      emptyTargets: sortedUnique(result.resolution.sources.flatMap((s) => s.entry.emptyTargets ?? [])),
    },
    binaryTargets: sortedUnique(input.products.flatMap((p) => p.binaryTargets)),
    products: input.products.map((p) => p.name),
  };
}
